PRAGMA journal_mode=WAL;
PRAGMA foreign_keys=ON;
PRAGMA synchronous=FULL;
PRAGMA busy_timeout=5000;
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY,body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS turns(id TEXT PRIMARY KEY,session_id TEXT NOT NULL REFERENCES sessions(id),state TEXT NOT NULL,body TEXT NOT NULL,created_at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS turns_session ON turns(session_id,created_at);
CREATE TABLE IF NOT EXISTS events(seq INTEGER PRIMARY KEY AUTOINCREMENT,session_id TEXT NOT NULL,turn_id TEXT NOT NULL,body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS interactions(id TEXT PRIMARY KEY,turn_id TEXT NOT NULL,state TEXT NOT NULL,body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS attempts(user_id INTEGER PRIMARY KEY,failures INTEGER NOT NULL,window_at INTEGER NOT NULL,blocked_until INTEGER NOT NULL,strikes INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS grants(user_id INTEGER PRIMARY KEY,epoch TEXT NOT NULL,last_used INTEGER NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS updates(id INTEGER PRIMARY KEY,state TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS routes(chat_id INTEGER PRIMARY KEY,provider TEXT,project_id TEXT,session_id TEXT);
CREATE TABLE IF NOT EXISTS outbox(id TEXT PRIMARY KEY,method TEXT NOT NULL,body TEXT NOT NULL,state TEXT NOT NULL DEFAULT 'queued',next_at INTEGER NOT NULL DEFAULT 0,attempts INTEGER NOT NULL DEFAULT 0,route_key TEXT);
CREATE INDEX IF NOT EXISTS outbox_due ON outbox(state,next_at);
CREATE TABLE IF NOT EXISTS telegram_messages(turn_id TEXT PRIMARY KEY,chat_id INTEGER NOT NULL,message_id INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit(seq INTEGER PRIMARY KEY AUTOINCREMENT,at INTEGER NOT NULL,action TEXT NOT NULL,target TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS assets(id TEXT PRIMARY KEY,body TEXT NOT NULL,created_at INTEGER NOT NULL);
PRAGMA user_version=1;
